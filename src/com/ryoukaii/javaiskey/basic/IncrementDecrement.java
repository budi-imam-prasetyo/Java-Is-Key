package com.ryoukaii.javaiskey.basic;

public class IncrementDecrement {
    public IncrementDecrement() {
        int x = 10;

        System.out.println();
        System.out.println("Increment dan Decrement");
        System.out.println(x++);
        System.out.println(++x);
        System.out.println(x--);
        System.out.println(--x);
    }
}
